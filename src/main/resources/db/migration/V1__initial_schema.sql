CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    account_role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_app_users_role CHECK (account_role IN ('ADMIN', 'OWNER', 'VIEWER'))
);

CREATE TABLE vault_documents (
    id UUID PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_users(id),
    title VARCHAR(180) NOT NULL,
    original_filename VARCHAR(180) NOT NULL,
    category VARCHAR(80) NOT NULL,
    description VARCHAR(1000),
    storage_key VARCHAR(80) NOT NULL UNIQUE,
    content_type VARCHAR(100) NOT NULL,
    size_bytes BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    deleted_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_vault_documents_owner ON vault_documents(owner_id, deleted_at);
CREATE INDEX ix_vault_documents_created ON vault_documents(created_at);
CREATE INDEX ix_vault_documents_category ON vault_documents(category);

CREATE TABLE document_grants (
    id UUID PRIMARY KEY,
    document_id UUID NOT NULL REFERENCES vault_documents(id),
    user_id BIGINT NOT NULL REFERENCES app_users(id),
    granted_by BIGINT NOT NULL REFERENCES app_users(id),
    permission VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_document_grant UNIQUE(document_id, user_id),
    CONSTRAINT ck_document_grant_permission CHECK (permission IN ('READ', 'EDIT'))
);
CREATE INDEX ix_document_grants_user ON document_grants(user_id);
CREATE INDEX ix_document_grants_document ON document_grants(document_id);

CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id BIGINT REFERENCES app_users(id),
    actor_email VARCHAR(254) NOT NULL,
    event_action VARCHAR(80) NOT NULL,
    resource_type VARCHAR(40) NOT NULL,
    resource_id VARCHAR(100),
    outcome VARCHAR(12) NOT NULL,
    details VARCHAR(2000),
    ip_address VARCHAR(64),
    user_agent VARCHAR(500),
    previous_hash VARCHAR(64) NOT NULL,
    event_hash VARCHAR(64) NOT NULL,
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS', 'DENIED', 'FAILURE'))
);
CREATE INDEX ix_audit_events_created ON audit_events(created_at DESC);
CREATE INDEX ix_audit_events_resource ON audit_events(resource_type, resource_id);
CREATE INDEX ix_audit_events_actor ON audit_events(actor_id);

CREATE TABLE audit_chain_state (
    id INTEGER PRIMARY KEY,
    last_hash VARCHAR(64) NOT NULL
);
